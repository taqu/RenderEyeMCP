class TestDecodeStructured:
    def _layout(self, stride, element_count, fields):
        return {"stride": stride, "element_count": element_count, "fields": fields}

    def test_single_uint32(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<II", 1, 2)
        layout = self._layout(4, 2, [{"name": "v", "type": "uint32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert "error" not in result
        assert result["element_count"] == 2
        assert result["elements"][0]["v"] == 1
        assert result["elements"][1]["v"] == 2

    def test_float32_vector(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<fff", 1.0, 2.0, 3.0)
        layout = self._layout(12, 1, [{"name": "pos", "type": "float32", "offset": 0, "components": 3}])
        result = _decode_structured(data, layout)
        assert "error" not in result
        assert result["elements"][0]["pos"] == pytest.approx([1.0, 2.0, 3.0])

    def test_float16(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<e", 0.5)
        layout = self._layout(2, 1, [{"name": "h", "type": "float16", "offset": 0}])
        result = _decode_structured(data, layout)
        assert "error" not in result
        assert abs(result["elements"][0]["h"] - 0.5) < 1e-3

    def test_nan_in_float(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<f", float("nan"))
        layout = self._layout(4, 1, [{"name": "f", "type": "float32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert "error" not in result
        assert result["elements"][0]["f"] == "nan"

    def test_inf_in_float(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<f", float("inf"))
        layout = self._layout(4, 1, [{"name": "f", "type": "float32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert result["elements"][0]["f"] == "inf"

    def test_neg_inf_in_float(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<f", float("-inf"))
        layout = self._layout(4, 1, [{"name": "f", "type": "float32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert result["elements"][0]["f"] == "-inf"

    def test_multiple_fields(self):
        from extensions.rendereye.gui_context import _decode_structured

        # position (12 bytes) + flags (4 bytes) = 16-byte stride
        data = struct.pack("<fffI", 1.0, 2.0, 3.0, 7)
        layout = self._layout(
            16, 1,
            [
                {"name": "position", "type": "float32", "offset": 0, "components": 3},
                {"name": "flags", "type": "uint32", "offset": 12},
            ],
        )
        result = _decode_structured(data, layout)
        assert "error" not in result
        elem = result["elements"][0]
        assert elem["position"] == pytest.approx([1.0, 2.0, 3.0])
        assert elem["flags"] == 7

    def test_int32_signed(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<i", -42)
        layout = self._layout(4, 1, [{"name": "v", "type": "int32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert result["elements"][0]["v"] == -42

    def test_int8_and_uint8(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = bytes([0xFF, 0x01])
        layout = self._layout(
            2, 1,
            [
                {"name": "u", "type": "uint8", "offset": 0},
                {"name": "s", "type": "int8", "offset": 1},
            ],
        )
        result = _decode_structured(data, layout)
        assert result["elements"][0]["u"] == 255
        assert result["elements"][0]["s"] == 1

    def test_uint64_and_int64(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<Qq", 2**63, -(2**62))
        layout = self._layout(
            16, 1,
            [
                {"name": "u", "type": "uint64", "offset": 0},
                {"name": "s", "type": "int64", "offset": 8},
            ],
        )
        result = _decode_structured(data, layout)
        assert result["elements"][0]["u"] == 2**63
        assert result["elements"][0]["s"] == -(2**62)

    def test_float64(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<d", 3.14159265358979)
        layout = self._layout(8, 1, [{"name": "pi", "type": "float64", "offset": 0}])
        result = _decode_structured(data, layout)
        assert result["elements"][0]["pi"] == pytest.approx(3.14159265358979, rel=1e-9)

    def test_element_count_capped_at_max(self):
        from extensions.rendereye.gui_context import _MAX_DECODE_ELEMENTS, _decode_structured

        data = struct.pack("<" + "I" * (_MAX_DECODE_ELEMENTS + 10), *range(_MAX_DECODE_ELEMENTS + 10))
        layout = self._layout(4, _MAX_DECODE_ELEMENTS + 10, [{"name": "v", "type": "uint32", "offset": 0}])
        result = _decode_structured(data, layout)
        assert result["element_count"] == _MAX_DECODE_ELEMENTS
        assert result["truncated"] is True

    def test_truncated_flag_false_when_not_truncated(self):
        from extensions.rendereye.gui_context import _decode_structured

        data = struct.pack("<II", 1, 2)
        layout = self._layout(4, 2, [{"name": "v", "type": "uint32", "offset": 0}])
