class TestInspectListResources:
    def _run(self, params, resources):
        gui, ctx = _make_gui()
        ctx.GetResources = MagicMock(return_value=resources)
        return gui.inspect("list_resources", params)

    def test_returns_all_resources(self):
        resources = [
            _make_resource("r1", "BufA", type_int=5),
            _make_resource("r2", "TexB", type_int=4),
        ]
        result = self._run({}, resources)
        assert "error" not in result
        assert result["total"] == 2
        assert len(result["resources"]) == 2

    def test_filter_by_buffer(self):
        resources = [
            _make_resource("r1", "BufA", type_int=5),
            _make_resource("r2", "TexB", type_int=4),
        ]
        result = self._run({"resource_type": "buffer"}, resources)
        assert result["total"] == 1
        assert result["resources"][0]["category"] == "buffer"

    def test_filter_by_texture(self):
        resources = [
            _make_resource("r1", "BufA", type_int=5),
            _make_resource("r2", "TexB", type_int=4),
        ]
        result = self._run({"resource_type": "texture"}, resources)
        assert result["total"] == 1
        assert result["resources"][0]["category"] == "texture"

    def test_name_filter_case_insensitive(self):
        resources = [
            _make_resource("r1", "SceneDepth", type_int=4),
        ]
        result = self._run({"name_filter": "SCENE"}, resources)
        assert result["total"] == 1

    def test_name_filter_no_match(self):
        resources = [
            _make_resource("r1", "SceneDepth", type_int=4),
        ]
        result = self._run({"name_filter": "XYZ"}, resources)
        assert result["total"] == 0
        assert result["resources"] == []

    def test_pagination_limit(self):
        resources = [_make_resource("r%d" % i, "Res%d" % i, type_int=5) for i in range(10)]
        result = self._run({"limit": 3}, resources)
        assert len(result["resources"]) == 3
        assert result["total"] == 10
        assert result["has_more"] is True

    def test_pagination_offset(self):
        resources = [_make_resource("r%d" % i, "Res%d" % i, type_int=5) for i in range(5)]
        result = self._run({"limit": 10, "offset": 3}, resources)
        assert len(result["resources"]) == 2
        assert result["has_more"] is False

    def test_has_more_false_when_exhausted(self):
        resources = [_make_resource("r%d" % i, "R%d" % i, type_int=5) for i in range(3)]
        result = self._run({"limit": 10}, resources)
        assert result["has_more"] is False

    def test_resource_fields(self):
        resources = [_make_resource("r1", "MyBuf", type_int=5, autogen=True)]
        result = self._run({}, resources)
        entry = result["resources"][0]
        assert entry["resource_id"] == "r1"
        assert entry["name"] == "MyBuf"
        assert entry["category"] == "buffer"
        assert entry["resource_type"] == 5

    def test_no_capture_loaded(self):
        gui, ctx = _make_gui()
        ctx.IsCaptureLoaded = MagicMock(return_value=False)
        ctx.IsCaptureLoading = MagicMock(return_value=False)
        result = gui.inspect("list_resources", {})
        assert result["error"] == "no_capture_loaded"

    def test_get_resources_error(self):
        gui, ctx = _make_gui()
        ctx.GetResources = MagicMock(side_effect=RuntimeError("API unavailable"))
        result = gui.inspect("list_resources", {})
        assert "error" in result

    def test_limit_capped_at_500(self):
        resources = [_make_resource("r%d" % i, "R%d" % i, type_int=5) for i in range(10)]
        gui, ctx = _make_gui()
