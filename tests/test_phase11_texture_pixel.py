    def test_image_data_extracted_to_image_content(self):
        import json as _json

        from mcp.types import ImageContent, TextContent

        png_b64 = base64.b64encode(b"PNG_FAKE_DATA").decode("ascii")
        result = {
            "resource_id": "resource-tex-1",
            "mip": 0,
            "width": 128,
            "height": 128,
            "format": "R8G8B8A8_UNORM",
            "image_data": png_b64,
            "mime_type": "image/png",
            "encoding": "base64",
            "byte_size": 14,
        }

        # Simulate the server extraction logic
        if isinstance(result, dict) and "image_data" in result:
            img_b64 = result.pop("image_data")
            content = [
                ImageContent(type="image", data=img_b64, mime_type="image/png"),
                TextContent(type="text", text=_json.dumps(result, indent=2)),
            ]
        else:
            content = result

