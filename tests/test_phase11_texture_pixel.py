class TestPackagingPhase11:
    def test_no_new_third_party_imports(self):
        """All Phase 11 imports (tempfile, os, base64, struct, zlib) are stdlib."""
        stdlib_names = {
            "os", "sys", "json", "socket", "threading", "time", "logging",
            "struct", "io", "collections", "functools", "contextlib",
            "traceback", "datetime", "re", "math", "copy", "types",
            "__future__", "abc", "enum", "dataclasses", "uuid", "hashlib",
            "pathlib", "tempfile", "shutil", "subprocess", "signal",
            "queue", "weakref", "inspect", "itertools", "operator",
            "base64", "zlib",
        }
        from pathlib import Path
        ext_dir = Path(__file__).parent.parent / "extensions" / "rendereye"
        for py_file in ext_dir.glob("*.py"):
            source = py_file.read_text(encoding="utf-8")
            for line in source.splitlines():
                line = line.strip()
                if not (line.startswith("import ") or line.startswith("from ")):
                    continue
                if line.startswith("from .") or line.startswith("from __future__"):
                    continue
                mod = line.split()[1].split(".")[0]
                if mod in stdlib_names:
                    continue
                if mod in {"gui_context", "gui_dispatcher", "ipc_client", "state_observer",
                           "renderdoc", "qrenderdoc"}:
                    continue
                assert False, f"{py_file.name}: potentially non-stdlib import {mod!r}"


